use serde::Serialize;
use serde_json::Value;
use std::collections::{HashMap, HashSet};

const TEXT_LIMIT: usize = 16 * 1024;
const RESULT_LIMIT: usize = 2 * 1024;
const SUBJECT_LIMIT: usize = 200;
/// How many ids a normalizer remembers across lines, per kind.
const MEMORY_LIMIT: usize = 4096;
/// Longer ids are not kept: each item of a line copies its entry's.
const ID_LIMIT: usize = 128;
const LINE_ITEMS_LIMIT: usize = 256;

/// Text the agent harness adds to the user's turn.
const INJECTED: &[&str] = &[
    "# AGENTS.md instructions",
    "<INSTRUCTIONS>",
    "<environment_context>",
    "<user_instructions>",
    "<permissions instructions>",
    "<collaboration_mode>",
    "<skills_instructions>",
    "<turn_aborted>",
    "<system-reminder>",
    "<local-command-",
    "<bash-stdout>",
    "<bash-stderr>",
    "<task-notification>",
    "<user-prompt-submit-hook>",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted by user",
    "This session is being continued from a previous conversation",
    "Goal mode is active.",
    "Continue the active /goal",
];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Provider {
    Omp,
    Pi,
    Claude,
    Codex,
}

impl Provider {
    pub fn parse(name: &str) -> Option<Self> {
        match name {
            "omp" => Some(Self::Omp),
            "pi" => Some(Self::Pi),
            "claude" => Some(Self::Claude),
            "codex" => Some(Self::Codex),
            _ => None,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Action {
    Read,
    Edit,
    Write,
    Run,
    Search,
    Web,
    Agent,
    Ask,
    Other,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum Item {
    User {
        id: String,
        text: String,
        images: usize,
        #[serde(skip_serializing_if = "is_false")]
        truncated: bool,
    },
    Assistant {
        id: String,
        text: String,
        #[serde(skip_serializing_if = "is_false")]
        truncated: bool,
    },
    Tool {
        id: String,
        name: String,
        action: Action,
        subject: Option<String>,
    },
    ToolResult {
        id: String,
        error: bool,
        text: Option<String>,
    },
}

fn is_false(value: &bool) -> bool {
    !value
}

/// The tool calls without result that end a history.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Pending {
    pub question: bool,
    pub call: bool,
}

impl Pending {
    pub fn of(items: &[Item]) -> Self {
        let mut answered = HashSet::new();
        let mut pending = Self::default();
        for item in items.iter().rev() {
            match item {
                Item::ToolResult { id, .. } => {
                    answered.insert(id.as_str());
                }
                Item::Tool { id, action, .. } if !answered.contains(id.as_str()) => {
                    pending.call = true;
                    pending.question |= *action == Action::Ask;
                }
                Item::Tool { .. } => {}
                Item::User { .. } | Item::Assistant { .. } => break,
            }
        }
        pending
    }

    /// Same rule as the page's `awaitingReply`: a question never answers itself, so it waits
    /// even while the agent reports work; another call only once the agent stopped.
    pub fn awaiting(self, working: Option<bool>) -> bool {
        self.question || (self.call && working != Some(true))
    }
}

/// Turns the lines of one history file into items, in order.
pub struct Normalizer {
    provider: Provider,
    /// Codex reports some failures in an event ahead of the output.
    failed: HashSet<String>,
    /// OMP's background commands, by job, until their end comes in a later entry.
    jobs: HashMap<String, String>,
    /// Goals already shown; their state is written again on every change.
    goals: HashSet<String>,
}

impl Normalizer {
    pub fn new(provider: Provider) -> Self {
        Self {
            provider,
            failed: HashSet::new(),
            jobs: HashMap::new(),
            goals: HashSet::new(),
        }
    }

    /// `offset` names the items of a line whose entry has no id, or one too long.
    pub fn line(&mut self, line: &[u8], offset: u64) -> Vec<Item> {
        let Ok(entry) = serde_json::from_slice::<Value>(line) else {
            return Vec::new();
        };
        let base = match self.provider {
            Provider::Omp | Provider::Pi => entry["id"].as_str(),
            Provider::Claude => entry["uuid"].as_str(),
            Provider::Codex => entry["payload"]["id"].as_str(),
        };
        let mut items = Items {
            base: base
                .filter(|base| base.len() <= ID_LIMIT)
                .map_or_else(|| offset.to_string(), str::to_owned),
            items: Vec::new(),
        };
        match self.provider {
            Provider::Omp | Provider::Pi => self.omp(&entry, &mut items),
            Provider::Claude => claude(&entry, &mut items),
            Provider::Codex => self.codex(&entry, &mut items),
        }
        items.items
    }

    fn codex(&mut self, entry: &Value, items: &mut Items) {
        let payload = &entry["payload"];
        let kind = payload["type"].as_str().unwrap_or_default();
        match entry["type"].as_str() {
            Some("response_item") => {}
            Some("event_msg") => {
                let failed = match kind {
                    "exec_command_end" => {
                        payload["exit_code"].as_i64().is_some_and(|code| code != 0)
                    }
                    "patch_apply_end" => payload["success"] == false,
                    _ => false,
                };
                if let (true, Some(id)) = (failed, payload["call_id"].as_str()) {
                    remember(&mut self.failed, id);
                }
                return;
            }
            _ => return,
        }
        match kind {
            "message" => match payload["role"].as_str() {
                Some("user") => {
                    let kinds = &payload["internal_chat_message_metadata_passthrough"]
                        ["content_item_kinds"];
                    let mut texts = Vec::new();
                    let mut images = 0;
                    for (index, part) in parts(&payload["content"]).enumerate() {
                        let typed = kinds[index].as_str().is_none_or(|kind| kind == "user.text");
                        match part {
                            Part::Text(text) if typed && !injected(text) => texts.push(text),
                            Part::Image => images += 1,
                            _ => {}
                        }
                    }
                    items.user(&texts.join("\n\n"), images);
                }
                Some("assistant") => items.assistant(&joined(&payload["content"])),
                _ => {}
            },
            "function_call" => {
                let arguments = payload["arguments"].as_str().map_or(Value::Null, |text| {
                    serde_json::from_str(text).unwrap_or(Value::Null)
                });
                items.tool(&payload["call_id"], name(payload), &arguments);
            }
            "custom_tool_call" => {
                let input = payload["input"].as_str().unwrap_or_default();
                let arguments = match (patch_path(input), script_command(input)) {
                    (Some(path), _) => serde_json::json!({ "path": path }),
                    (None, Some(cmd)) => serde_json::json!({ "cmd": cmd }),
                    (None, None) => Value::Null,
                };
                items.tool(&payload["call_id"], name(payload), &arguments);
            }
            "local_shell_call" => {
                items.tool(&payload["call_id"], "shell", &payload["action"]);
            }
            "web_search_call" => {
                let id = payload["id"]
                    .as_str()
                    .map(|id| Value::String(id.to_owned()));
                let id = id.unwrap_or_else(|| Value::String(items.next_id()));
                items.tool(&id, "web_search", &payload["action"]);
                items.result(&id, false, "");
            }
            _ if kind.ends_with("_output") => {
                let (text, failed) = codex_output(&payload["output"]);
                let id = payload["call_id"].as_str().unwrap_or_default();
                let failed = failed || self.failed.remove(id);
                items.result(&payload["call_id"], failed, &text);
            }
            _ => {}
        }
    }

    fn omp(&mut self, entry: &Value, items: &mut Items) {
        let message = &entry["message"];
        match (entry["type"].as_str(), message["role"].as_str()) {
            (Some("message"), Some("user")) if message["attribution"] != "agent" => {
                let mut texts = Vec::new();
                let mut images = 0;
                for part in parts(&message["content"]) {
                    match part {
                        Part::Text(text) => texts.push(text),
                        Part::Image => images += 1,
                        Part::Other(_) => {}
                    }
                }
                let text = texts.join("\n\n");
                if !injected(&text) {
                    items.user(&text, images);
                }
            }
            (Some("message"), Some("assistant")) => {
                assistant_parts(&message["content"], items, "toolCall", "arguments");
            }
            (Some("message"), Some("toolResult")) => {
                let error = message["isError"] == true;
                items.result(&message["toolCallId"], error, &joined(&message["content"]));
                let job = &message["details"]["async"];
                if let (true, Some(job), Some(call)) = (
                    job["state"] == "running" && job["type"] == "bash",
                    job["jobId"].as_str(),
                    message["toolCallId"].as_str(),
                ) {
                    if job.len() <= ID_LIMIT && call.len() <= ID_LIMIT {
                        if self.jobs.len() >= MEMORY_LIMIT {
                            self.jobs.clear();
                        }
                        self.jobs.insert(job.to_owned(), call.to_owned());
                    }
                }
            }
            (Some("custom_message"), _) if entry["customType"] == "async-result" => {
                let content = entry["content"].as_str().unwrap_or_default();
                for job in entry["details"]["jobs"].as_array().into_iter().flatten() {
                    let Some(id) = job["jobId"].as_str() else {
                        continue;
                    };
                    if let Some(call) = self.jobs.remove(id) {
                        let output = job_output(content, id);
                        let failed = omp_job_failed(output);
                        items.result(&Value::String(call), failed, output);
                    }
                }
            }
            (Some("custom_message"), _)
                if entry["customType"] == "skill-prompt" && entry["attribution"] != "agent" =>
            {
                items.user(entry["details"]["prompt"].as_str().unwrap_or_default(), 0);
            }
            // Pi records the objective of `/goal` only here and in its injected contract.
            (Some("custom"), _) if entry["customType"] == "goal-state" => {
                let goal = &entry["data"]["goal"];
                if let (true, Some(id)) = (goal["status"] == "active", goal["id"].as_str()) {
                    if id.len() <= ID_LIMIT && !self.goals.contains(id) {
                        remember(&mut self.goals, id);
                        items.user(goal["text"].as_str().unwrap_or_default(), 0);
                    }
                }
            }
            _ => {}
        }
    }
}

fn name(payload: &Value) -> &str {
    payload["name"].as_str().unwrap_or_default()
}

struct Items {
    base: String,
    items: Vec<Item>,
}

impl Items {
    fn next_id(&self) -> String {
        format!("{}:{}", self.base, self.items.len())
    }

    /// A line crafted with countless parts stops producing items here.
    fn full(&self) -> bool {
        self.items.len() >= LINE_ITEMS_LIMIT
    }

    fn user(&mut self, text: &str, images: usize) {
        let text = text.trim();
        if (text.is_empty() && images == 0) || self.full() {
            return;
        }
        let (text, truncated) = bounded(text, TEXT_LIMIT);
        self.items.push(Item::User {
            id: self.next_id(),
            text,
            images,
            truncated,
        });
    }

    fn assistant(&mut self, text: &str) {
        let text = text.trim();
        if text.is_empty() || self.full() {
            return;
        }
        let (text, truncated) = bounded(text, TEXT_LIMIT);
        self.items.push(Item::Assistant {
            id: self.next_id(),
            text,
            truncated,
        });
    }

    fn tool(&mut self, id: &Value, name: &str, arguments: &Value) {
        let Some(id) = id.as_str().filter(|id| !id.is_empty() && !self.full()) else {
            return;
        };
        let name = name.rsplit("__").next().unwrap_or(name);
        let action = action(name);
        self.items.push(Item::Tool {
            id: id.to_owned(),
            name: name.to_owned(),
            action,
            subject: subject(action, arguments),
        });
    }

    fn result(&mut self, id: &Value, error: bool, text: &str) {
        let Some(id) = id.as_str().filter(|id| !id.is_empty() && !self.full()) else {
            return;
        };
        let text = text.trim();
        self.items.push(Item::ToolResult {
            id: id.to_owned(),
            error,
            text: (!text.is_empty()).then(|| bounded(text, RESULT_LIMIT).0),
        });
    }
}

enum Part<'a> {
    Text(&'a str),
    Image,
    Other(&'a Value),
}

/// A plain string content counts as one text part.
fn parts(content: &Value) -> impl Iterator<Item = Part<'_>> {
    let single = content.as_str().map(Part::Text);
    let list = content.as_array().into_iter().flatten().map(|part| {
        match (
            part["type"].as_str().unwrap_or_default(),
            part["text"].as_str(),
        ) {
            ("text" | "input_text" | "output_text" | "Text", Some(text)) => Part::Text(text),
            ("image" | "input_image", _) => Part::Image,
            _ => Part::Other(part),
        }
    });
    single.into_iter().chain(list)
}

fn joined(content: &Value) -> String {
    let texts: Vec<&str> = parts(content)
        .filter_map(|part| match part {
            Part::Text(text) => Some(text),
            _ => None,
        })
        .collect();
    texts.join("\n\n")
}

fn injected(text: &str) -> bool {
    let text = text.trim_start();
    INJECTED.iter().any(|prefix| text.starts_with(prefix))
}

/// The assistant's text and tool calls of one entry, in order; thinking is left out.
fn assistant_parts(content: &Value, items: &mut Items, call: &str, input: &str) {
    let mut text = Vec::new();
    for part in parts(content) {
        match part {
            Part::Text(part) => text.push(part),
            Part::Other(part) if part["type"] == call => {
                items.assistant(&text.join("\n\n"));
                text.clear();
                items.tool(&part["id"], name(part), &part[input]);
            }
            _ => {}
        }
    }
    items.assistant(&text.join("\n\n"));
}

fn claude(entry: &Value, items: &mut Items) {
    if ["isMeta", "isSidechain", "isCompactSummary"]
        .iter()
        .any(|flag| entry[flag] == true)
    {
        return;
    }
    let content = &entry["message"]["content"];
    match entry["type"].as_str() {
        Some("user") => {
            let mut texts = Vec::new();
            let mut images = 0;
            let mut results = false;
            for part in parts(content) {
                match part {
                    Part::Text(text) => texts.extend(claude_command(text)),
                    Part::Image => images += 1,
                    Part::Other(part) if part["type"] == "tool_result" => {
                        results = true;
                        let error = part["is_error"] == true;
                        items.result(&part["tool_use_id"], error, &joined(&part["content"]));
                    }
                    Part::Other(_) => {}
                }
            }
            // Next to tool results, text comes from Claude Code, not from the user.
            if !results {
                items.user(&texts.join("\n\n"), images);
            }
        }
        Some("assistant") => assistant_parts(content, items, "tool_use", "input"),
        // Recent Claude Code records a slash command and its output this way.
        Some("system") if entry["subtype"] == "local_command" => {
            let command = entry["content"].as_str().and_then(claude_command);
            items.user(&command.unwrap_or_default(), 0);
        }
        _ => {}
    }
}

/// A slash command or shell escape as the user typed it; `None` for injected text.
fn claude_command(text: &str) -> Option<String> {
    let tag = |name: &str| {
        let (_, rest) = text.split_once(&format!("<{name}>"))?;
        let (value, _) = rest.split_once(&format!("</{name}>"))?;
        Some(value.trim())
    };
    let trimmed = text.trim_start();
    if trimmed.starts_with("<command-") {
        let command = tag("command-name")?;
        let args = tag("command-args").unwrap_or_default();
        return Some(format!("{command} {args}").trim_end().to_owned());
    }
    if trimmed.starts_with("<bash-input>") {
        return Some(format!("!{}", tag("bash-input")?));
    }
    (!injected(text)).then(|| text.to_owned())
}

/// The output text, with code-mode chunks reduced to their output, and whether it reports a failure.
fn codex_output(output: &Value) -> (String, bool) {
    let mut failed = false;
    let mut texts = Vec::new();
    for part in parts(output) {
        let Part::Text(text) = part else {
            continue;
        };
        let parsed = serde_json::from_str::<Value>(text).ok();
        let code = parsed.as_ref().and_then(|value| {
            value["exit_code"]
                .as_i64()
                .or_else(|| value["metadata"]["exit_code"].as_i64())
        });
        failed |= code.is_some_and(|code| code != 0) || codex_exit(text);
        let output = parsed.as_ref().and_then(|value| value["output"].as_str());
        texts.push(output.unwrap_or(text).trim().to_owned());
    }
    (texts.join("\n"), failed)
}

/// Codex heads a command output with its exit code, above the `Output:` line.
fn codex_exit(text: &str) -> bool {
    let mut failed = false;
    for line in text.lines() {
        if line == "Output:" {
            return failed;
        }
        failed |=
            nonzero_exit(line, "Exit code: ") || nonzero_exit(line, "Process exited with code ");
    }
    false
}

/// OMP follows a command output with its duration, then with its exit code or its timeout.
fn omp_job_failed(output: &str) -> bool {
    let mut failed = false;
    for line in output.lines().rev() {
        if line.starts_with("Wall time: ") && line.ends_with(" seconds") {
            return failed;
        }
        failed |= nonzero_exit(line, "Command exited with code ")
            || line.starts_with("[Command timed out after ");
    }
    false
}

fn nonzero_exit(line: &str, prefix: &str) -> bool {
    line.strip_prefix(prefix)
        .and_then(|code| code.trim().parse::<i64>().ok())
        .is_some_and(|code| code != 0)
}

/// What OMP delivers of job `id` in a notice that may gather several jobs.
fn job_output<'a>(content: &'a str, id: &str) -> &'a str {
    let content = content.trim();
    let content = content.strip_prefix("<system-notice>").unwrap_or(content);
    let content = content.strip_suffix("</system-notice>").unwrap_or(content);
    let section = format!("\n── Job {id} (");
    let Some(start) = content.find(&section) else {
        // A single job, after its heading line.
        return content
            .trim_start()
            .split_once('\n')
            .map_or("", |(_, output)| output);
    };
    let output = &content[start + 1..];
    let output = output.split_once('\n').map_or("", |(_, output)| output);
    output.split("\n── Job ").next().unwrap_or(output)
}

fn remember(ids: &mut HashSet<String>, id: &str) {
    if id.len() > ID_LIMIT {
        return;
    }
    if ids.len() >= MEMORY_LIMIT {
        ids.clear();
    }
    ids.insert(id.to_owned());
}

/// The first file of an `apply_patch` input.
fn patch_path(input: &str) -> Option<&str> {
    input.lines().find_map(|line| {
        ["*** Update File: ", "*** Add File: ", "*** Delete File: "]
            .iter()
            .find_map(|prefix| line.strip_prefix(prefix))
    })
}

/// The first `cmd` of a code-mode script, `tools.exec_command({cmd:"…"})`.
fn script_command(input: &str) -> Option<String> {
    let start = ["cmd:", "\"cmd\":"]
        .iter()
        .filter_map(|key| input.find(key).map(|index| index + key.len()))
        .min()?;
    let rest = input[start..].trim_start().strip_prefix('"')?;
    let mut escaped = false;
    let end = rest.char_indices().find_map(|(index, c)| {
        let end = !escaped && c == '"';
        escaped = !escaped && c == '\\';
        end.then_some(index)
    })?;
    serde_json::from_str(&format!("\"{}\"", &rest[..end])).ok()
}

fn action(name: &str) -> Action {
    let name = name.to_ascii_lowercase();
    match name.as_str() {
        "read" | "read_file" | "view" | "view_image" | "notebookread" => Action::Read,
        "edit" | "multiedit" | "notebookedit" | "apply_patch" | "ast_edit" | "str_replace" => {
            Action::Edit
        }
        "write" | "write_file" | "create_file" => Action::Write,
        "bash" | "shell" | "shell_command" | "local_shell" | "exec" | "exec_command"
        | "write_stdin" | "eval" | "bashoutput" | "killshell" => Action::Run,
        "grep" | "glob" | "find" | "search" | "ls" | "ast_grep" => Action::Search,
        "web_search" | "websearch" | "webfetch" | "web_fetch" | "fetch" | "fetch_content"
        | "browser" => Action::Web,
        "ask" | "askuserquestion" | "ask_user_question" | "request_user_input" => Action::Ask,
        "task" => Action::Agent,
        _ if name.contains("agent") => Action::Agent,
        _ => Action::Other,
    }
}

fn subject(action: Action, arguments: &Value) -> Option<String> {
    let keys: &[&str] = match action {
        Action::Read | Action::Edit | Action::Write => &["path", "file_path", "notebook_path"],
        Action::Run => &["command", "cmd", "title", "code"],
        Action::Search => &["pattern", "query", "path"],
        Action::Web => &["url", "query", "urls", "queries"],
        Action::Agent => &["description", "name", "subagent_type", "prompt"],
        Action::Ask => &["question"],
        Action::Other => &[
            "path",
            "file_path",
            "command",
            "query",
            "url",
            "description",
        ],
    };
    let first = |value: &Value| keys.iter().find_map(|key| text(&value[key]));
    let found = first(arguments).or_else(|| match action {
        // OMP's patch starts with `[path#tag]`.
        Action::Edit => arguments["input"]
            .as_str()
            .and_then(|input| input.strip_prefix('['))
            .and_then(|input| input.split(['#', ']']).next())
            .map(str::to_owned),
        Action::Agent => first(&arguments["tasks"][0]),
        Action::Ask => text(&arguments["questions"][0]["question"]),
        _ => None,
    })?;
    one_line(&found)
}

/// A string, or a command line given as an array (`["bash", "-lc", "…"]` keeps the script).
fn text(value: &Value) -> Option<String> {
    if let Some(text) = value.as_str() {
        return Some(text.to_owned());
    }
    let words: Vec<&str> = value.as_array()?.iter().filter_map(Value::as_str).collect();
    match words.as_slice() {
        [_, "-c" | "-lc", script] => Some((*script).to_owned()),
        _ if words.is_empty() => None,
        _ => Some(words.join(" ")),
    }
}

fn one_line(text: &str) -> Option<String> {
    let line = text.split_whitespace().collect::<Vec<_>>().join(" ");
    if line.is_empty() {
        return None;
    }
    if line.chars().count() <= SUBJECT_LIMIT {
        return Some(line);
    }
    let mut cut: String = line.chars().take(SUBJECT_LIMIT - 1).collect();
    cut.push('…');
    Some(cut)
}

/// At most `limit` bytes, cut on a character boundary.
fn bounded(text: &str, limit: usize) -> (String, bool) {
    if text.len() <= limit {
        return (text.to_owned(), false);
    }
    let mut end = limit;
    while !text.is_char_boundary(end) {
        end -= 1;
    }
    (text[..end].to_owned(), true)
}

